#!/usr/bin/env python3
"""Generates the native API's clients from its contract, api/openapi.json (M221, M222).

    scripts/gen-clients.py           write the generated files
    scripts/gen-clients.py --check   exit 1 when a generated file is not what this writes

Rung 5 of gate-design: the clients are generated, never maintained, and --check is the gate
that a contract change regenerated them. Standard library only, so it runs wherever the
other gates run. Each output names the contract's version and digest, so a client built from
another contract says which.
"""

from __future__ import annotations

import hashlib
import json
import keyword
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SPEC = ROOT / "api" / "openapi.json"
METHODS = ("get", "put", "post", "patch", "delete")


def load() -> tuple[dict, str]:
    raw = SPEC.read_bytes()
    return json.loads(raw), hashlib.sha256(raw).hexdigest()


def camel(s: str) -> str:
    head, *rest = s.split("_")
    return head + "".join(w[:1].upper() + w[1:] for w in rest)


def ref_name(s: dict) -> str | None:
    r = s.get("$ref")
    return r.rsplit("/", 1)[-1] if isinstance(r, str) else None


class Op:
    """One operation, as both generators read it."""

    def __init__(self, spec: dict, path: str, method: str, o: dict):
        self.id = o["operationId"]
        self.method = method.upper()
        self.path = path
        self.summary = o.get("summary", "")
        self.scope = o["security"][0]["bearer"][0]
        params = []
        for p in o.get("parameters", []):
            if "$ref" in p:
                p = spec["components"]["parameters"][ref_name(p)]
            params.append(p)
        self.path_params = [p["name"] for p in params if p["in"] == "path"]
        self.query = [p for p in params if p["in"] == "query"]
        self.session = any(p["in"] == "header" and p["name"] == "x-pstore-session" for p in params)
        body = o.get("requestBody")
        self.body = None
        self.body_required = False
        if body:
            self.body = body["content"]["application/json"]["schema"]
            self.body_required = bool(body.get("required"))
        self.responses = {}
        self.text = False
        for status, r in o["responses"].items():
            if not status.startswith("2"):
                continue
            content = r.get("content", {})
            if "text/plain" in content:
                self.text = True
            self.responses[status] = content.get("application/json", {}).get("schema")


def operations(spec: dict) -> list[Op]:
    out = []
    for path, item in spec["paths"].items():
        for m in METHODS:
            if m in item:
                out.append(Op(spec, path, m, item[m]))
    return out


# --- Python -----------------------------------------------------------------------------


def py_type(s: dict | None) -> str:
    if not s:
        return "Any"
    name = ref_name(s)
    if name:
        return f'"{name}"'
    if "oneOf" in s:
        return "Union[" + ", ".join(py_type(a) for a in s["oneOf"]) + "]"
    t = s.get("type")
    if isinstance(t, list):
        return "Union[" + ", ".join(py_type(dict(s, type=x)) for x in t) + "]"
    if t == "string":
        return "str"
    if t == "integer":
        return "int"
    if t == "number":
        return "float"
    if t == "boolean":
        return "bool"
    if t == "null":
        return "None"
    if t == "array":
        return f"List[{py_type(s.get('items'))}]"
    if t == "object":
        extra = s.get("additionalProperties")
        if not s.get("properties") and isinstance(extra, dict):
            return f"Dict[str, {py_type(extra)}]"
        return "Dict[str, Any]"
    return "Any"


def py_doc(text: str, indent: str) -> str:
    text = text.replace("\\", "\\\\").replace('"""', '\\"\\"\\"')
    return f'{indent}"""{text}"""\n'


def python(spec: dict, digest: str) -> str:
    version = spec["info"]["version"]
    out = [
        f"# Generated by scripts/gen-clients.py from api/openapi.json {version}\n",
        f"# (sha256 {digest}). Do not edit: change the contract and regenerate.\n",
        '"""pstore\'s native API, one method per operation (M221).\n\n'
        "Standard library only. Each method returns the answer's JSON (text for `metrics`), with\n"
        "its status in `Client.last_status`, and raises `PstoreError` for a status of 400 or more.\n"
        '"""\n\n',
        "from __future__ import annotations\n\n",
        "import json\n",
        "import urllib.error\n",
        "import urllib.parse\n",
        "import urllib.request\n",
        "from typing import Any, Dict, List, Optional, TypedDict, Union\n\n",
        f'CONTRACT_VERSION = "{version}"\n',
        f'CONTRACT_SHA256 = "{digest}"\n\n',
        "__all__ = [\"Client\", \"PstoreError\", \"CONTRACT_VERSION\", \"CONTRACT_SHA256\"]\n\n",
    ]
    for name, s in spec["components"]["schemas"].items():
        props = s.get("properties")
        if s.get("type") == "object" and props is not None:
            fields = ", ".join(f'"{k}": {py_type(v)}' for k, v in props.items())
            out.append(f'{name} = TypedDict("{name}", {{{fields}}}, total=False)\n')
        else:
            out.append(f"{name} = {py_type(s).strip(chr(34))}\n" if not ref_name(s) else f"{name} = Any\n")
        if s.get("description"):
            out.append(f"# {name}: {s['description']}\n")
        out.append("\n")
    out.append(PY_RUNTIME)
    for op in operations(spec):
        args = ["self"] + [f"{p}: str" for p in op.path_params]
        if op.body is not None:
            t = py_type(op.body)
            args.append(f"body: {t}" if op.body_required else f"body: Optional[{t}] = None")
        kw = []
        for q in op.query:
            n = q["name"] + ("_" if keyword.iskeyword(q["name"]) else "")
            kw.append(f"{n}: Optional[{py_type(q['schema']).strip(chr(34))}] = None")
        if op.session:
            kw.append("session: Optional[str] = None")
        if kw:
            args += ["*"] + kw
        ret = "str" if op.text else (
            "Union[" + ", ".join(py_type(r) for r in op.responses.values()) + "]"
            if len({json.dumps(r) for r in op.responses.values()}) > 1
            else py_type(next(iter(op.responses.values()), None))
        )
        out.append(f"    def {op.id}({', '.join(args)}) -> {ret}:\n")
        doc = f"{op.method} {op.path} (scope `{op.scope}`): {op.summary}"
        out.append(py_doc(doc, "        "))
        path = op.path
        for p in op.path_params:
            path = path.replace("{" + p + "}", "{_seg(" + p + ")}")
        query = ", ".join(
            f'("{q["name"]}", {q["name"] + ("_" if keyword.iskeyword(q["name"]) else "")})'
            for q in op.query
        )
        call = [f'"{op.method}"', f'f"{path}"', f'"{op.id}"']
        if op.query:
            call.append(f"query=[{query}]")
        if op.body is not None:
            call.append("body=body")
        if op.session:
            call.append("session=session")
        if op.text:
            call.append("text=True")
        out.append(f"        return self._call({', '.join(call)})\n\n")
    out.append(
        "    OPERATIONS = (\n"
        + "".join(f'        "{op.id}",\n' for op in operations(spec))
        + "    )\n"
    )
    return "".join(out)


PY_RUNTIME = '''
class PstoreError(Exception):
    """A refusal: `code` is stable across releases, `message` is for a human."""

    def __init__(self, status: int, code: str, message: str, retryable: bool,
                 retry_after: Optional[int] = None, body: Any = None) -> None:
        super().__init__(f"{status} {code}: {message}")
        self.status = status
        self.code = code
        self.message = message
        self.retryable = retryable
        self.retry_after = retry_after
        self.body = body


def _seg(v: str) -> str:
    return urllib.parse.quote(str(v), safe="")


def _qv(v: Any) -> str:
    if isinstance(v, bool):
        return "true" if v else "false"
    return str(v)


class Client:
    """A client for one pstore server.

    `token` is a bearer token (M127); `tenant` is sent as `x-pstore-tenant`, which only an
    unsecured deployment reads. `last_session` holds the `x-pstore-session` the latest answer
    returned, to pass as `session=` for a read that must see that write (M11.1). `last_status`
    holds the latest success's status, which some operations answer with meaning: `copy_index`
    is 202 when this request started the copy and 200 when an earlier one had.
    """

    def __init__(self, base_url: str, *, token: Optional[str] = None,
                 tenant: Optional[str] = None, timeout: float = 30.0) -> None:
        self.base_url = base_url.rstrip("/")
        self.token = token
        self.tenant = tenant
        self.timeout = timeout
        self.last_session: Optional[str] = None
        self.last_status: Optional[int] = None

    def _call(self, method: str, path: str, operation: str, *, query: Any = (),
              body: Any = None, session: Optional[str] = None, text: bool = False) -> Any:
        url = self.base_url + path
        pairs = [(k, _qv(v)) for k, v in query if v is not None]
        if pairs:
            url += "?" + urllib.parse.urlencode(pairs)
        headers = {"accept": "text/plain" if text else "application/json"}
        data = None
        if body is not None:
            data = json.dumps(body).encode()
            headers["content-type"] = "application/json"
        if self.token is not None:
            headers["authorization"] = f"Bearer {self.token}"
        if self.tenant is not None:
            headers["x-pstore-tenant"] = str(self.tenant)
        if session is not None:
            headers["x-pstore-session"] = session
        req = urllib.request.Request(url, data=data, method=method, headers=headers)
        try:
            with urllib.request.urlopen(req, timeout=self.timeout) as res:
                raw = res.read()
                self.last_status = res.status
                self.last_session = res.headers.get("x-pstore-session", self.last_session)
                return raw.decode() if text else json.loads(raw)
        except urllib.error.HTTPError as e:
            raw = e.read()
            after = e.headers.get("retry-after")
            retry_after = int(after) if after and after.isdigit() else None
            try:
                parsed = json.loads(raw)
                err = parsed["error"]
            except (ValueError, KeyError, TypeError):
                raise PstoreError(e.code, "unparsed", raw.decode(errors="replace"),
                                  e.code >= 500 or e.code == 429, retry_after, raw) from None
            raise PstoreError(e.code, err.get("code", ""), err.get("message", ""),
                              bool(err.get("retryable")), retry_after, parsed) from None

'''


# --- TypeScript -------------------------------------------------------------------------


def ts_type(s: dict | None) -> str:
    if not s:
        return "unknown"
    name = ref_name(s)
    if name:
        return name
    if "oneOf" in s:
        return " | ".join(ts_type(a) for a in s["oneOf"])
    if "enum" in s:
        return " | ".join("null" if e is None else json.dumps(e) for e in s["enum"])
    t = s.get("type")
    if isinstance(t, list):
        return " | ".join(ts_type(dict(s, type=x)) for x in t)
    if t == "string":
        return "string"
    if t in ("integer", "number"):
        return "number"
    if t == "boolean":
        return "boolean"
    if t == "null":
        return "null"
    if t == "array":
        inner = ts_type(s.get("items"))
        return f"Array<{inner}>"
    if t == "object":
        props = s.get("properties")
        extra = s.get("additionalProperties")
        if props:
            return ts_object(s)
        if isinstance(extra, dict):
            return f"{{ [key: string]: {ts_type(extra)} }}"
        return "{ [key: string]: unknown }"
    return "unknown"


def ts_object(s: dict, indent: str = "") -> str:
    req = set(s.get("required", []))
    lines = ["{"]
    for k, v in s["properties"].items():
        if v.get("description"):
            lines.append(f"{indent}  /** {ts_comment(v['description'])} */")
        lines.append(f"{indent}  {json.dumps(k)}{'' if k in req else '?'}: {ts_type(v)};")
    lines.append(indent + "}")
    return "\n".join(lines)


def ts_comment(text: str) -> str:
    return text.replace("*/", "* /")


def typescript(spec: dict, digest: str) -> str:
    version = spec["info"]["version"]
    out = [
        f"// Generated by scripts/gen-clients.py from api/openapi.json {version}\n",
        f"// (sha256 {digest}). Do not edit: change the contract and regenerate.\n",
        "//\n",
        "// pstore's native API, one method per operation (M222). Dependency-free: it needs only\n",
        "// `fetch`. Each method resolves to the answer's JSON (text for `metrics`), with its status\n",
        "// in `Client.lastStatus`, and rejects with `PstoreError` for any status that is not 2xx.\n",
        "// An `Id` above 2**53 (a uint64 index) is not exact: `JSON.parse` reads it as a double.\n\n",
        f'export const CONTRACT_VERSION = "{version}";\n',
        f'export const CONTRACT_SHA256 = "{digest}";\n\n',
    ]
    for name, s in spec["components"]["schemas"].items():
        if s.get("description"):
            out.append(f"/** {ts_comment(s['description'])} */\n")
        out.append(f"export type {name} = {ts_type(s) if ref_name(s) is None else 'unknown'};\n\n")
    out.append(TS_RUNTIME)
    for op in operations(spec):
        args = [f"{p}: string" for p in op.path_params]
        if op.body is not None:
            t = ts_type(op.body)
            args.append(f"body: {t}" if op.body_required else f"body?: {t}")
        opts = [f"{q['name']}?: {ts_type(q['schema'])}" for q in op.query]
        if op.session:
            opts.append("session?: string")
        if opts:
            args.append(f"options: {{ {'; '.join(opts)} }} = {{}}")
        if op.text:
            ret = "string"
        else:
            kinds = {json.dumps(r) for r in op.responses.values()}
            ret = " | ".join(ts_type(r) for r in op.responses.values()) if len(kinds) > 1 else ts_type(next(iter(op.responses.values()), None))
        path = op.path
        for p in op.path_params:
            path = path.replace("{" + p + "}", "${seg(" + p + ")}")
        out.append(f"  /** {op.method} {op.path} (scope `{op.scope}`): {ts_comment(op.summary)} */\n")
        out.append(f"  {camel(op.id)}({', '.join(args)}): Promise<{ret}> {{\n")
        call = [json.dumps(op.method), f"`{path}`", "{"]
        fields = []
        if op.query:
            fields.append("query: [" + ", ".join(f'["{q["name"]}", options.{q["name"]}]' for q in op.query) + "]")
        if op.body is not None:
            fields.append("body")
        if op.session:
            fields.append("session: options.session")
        if op.text:
            fields.append("text: true")
        out.append(f"    return this.call({json.dumps(op.method)}, `{path}`, {{ {', '.join(fields)} }}) as Promise<{ret}>;\n")
        out.append("  }\n\n")
    out.append("}\n\n")
    out.append("/**\n * Each operationId: the method that calls it, its path parameters in argument order, and\n")
    out.append(" * whether a body and then an options object follow them.\n */\n")
    out.append("export const OPERATIONS = {\n")
    for op in operations(spec):
        has_opts = bool(op.query) or op.session
        out.append(
            f'  {op.id}: {{ method: "{camel(op.id)}", path: {json.dumps(op.path_params)}, '
            f'body: {str(op.body is not None).lower()}, options: {str(has_opts).lower()} }},\n'
        )
    out.append("} as const;\n")
    return "".join(out)


TS_RUNTIME = """/** A refusal: `code` is stable across releases, `message` is for a human. */
export class PstoreError extends Error {
  readonly status: number;
  readonly code: string;
  readonly retryable: boolean;
  readonly retryAfter: number | undefined;
  readonly body: unknown;

  constructor(status: number, code: string, message: string, retryable: boolean,
              retryAfter: number | undefined, body: unknown) {
    super(`${status} ${code}: ${message}`);
    this.name = "PstoreError";
    this.status = status;
    this.code = code;
    this.retryable = retryable;
    this.retryAfter = retryAfter;
    this.body = body;
  }
}

/** How a client reaches one server. */
export interface ClientOptions {
  baseUrl: string;
  /** A bearer token (M127). */
  token?: string;
  /** Sent as `x-pstore-tenant`, which only an unsecured deployment reads. */
  tenant?: string;
  /** The `fetch` to call; the global one when absent. */
  fetch?: typeof fetch;
}

interface Call {
  query?: Array<[string, unknown]>;
  body?: unknown;
  session?: string;
  text?: boolean;
}

function seg(v: string): string {
  return encodeURIComponent(String(v));
}

function qv(v: unknown): string {
  return typeof v === "boolean" ? (v ? "true" : "false") : String(v);
}

/**
 * A client for one pstore server. `lastSession` holds the `x-pstore-session` the latest answer
 * returned, to pass as `session` for a read that must see that write (M11.1). `lastStatus` holds
 * the latest success's status: `copyIndex` is 202 when this request started the copy and 200
 * when an earlier one had.
 */
export class Client {
  readonly baseUrl: string;
  readonly token: string | undefined;
  readonly tenant: string | undefined;
  lastSession: string | undefined;
  lastStatus: number | undefined;
  private readonly fetcher: typeof fetch;

  constructor(options: ClientOptions) {
    this.baseUrl = options.baseUrl.replace(/\\/+$/, "");
    this.token = options.token;
    this.tenant = options.tenant;
    this.fetcher = options.fetch ?? globalThis.fetch.bind(globalThis);
  }

  private async call(method: string, path: string, c: Call): Promise<unknown> {
    const pairs = (c.query ?? []).filter(([, v]) => v !== undefined && v !== null)
      .map(([k, v]) => `${encodeURIComponent(k)}=${encodeURIComponent(qv(v))}`);
    const url = this.baseUrl + path + (pairs.length ? `?${pairs.join("&")}` : "");
    const headers: Record<string, string> = { accept: c.text ? "text/plain" : "application/json" };
    if (c.body !== undefined) headers["content-type"] = "application/json";
    if (this.token !== undefined) headers["authorization"] = `Bearer ${this.token}`;
    if (this.tenant !== undefined) headers["x-pstore-tenant"] = this.tenant;
    if (c.session !== undefined) headers["x-pstore-session"] = c.session;
    const res = await this.fetcher(url, {
      method,
      headers,
      body: c.body === undefined ? undefined : JSON.stringify(c.body),
    });
    const raw = await res.text();
    if (res.ok) {
      this.lastStatus = res.status;
      this.lastSession = res.headers.get("x-pstore-session") ?? this.lastSession;
      return c.text ? raw : JSON.parse(raw);
    }
    let parsed: unknown;
    try {
      parsed = JSON.parse(raw);
    } catch {
      parsed = undefined;
    }
    const err = (parsed as { error?: { code?: string; message?: string; retryable?: boolean } } | undefined)?.error;
    const after = res.headers.get("retry-after");
    const retryAfter = after && /^[0-9]+$/.test(after) ? Number(after) : undefined;
    if (!err) {
      throw new PstoreError(res.status, "unparsed", raw, res.status >= 500 || res.status === 429, retryAfter, raw);
    }
    throw new PstoreError(res.status, err.code ?? "", err.message ?? "", Boolean(err.retryable),
      retryAfter, parsed);
  }

"""


def main() -> int:
    spec, digest = load()
    files = {
        ROOT / "clients" / "python" / "pstore_client" / "__init__.py": python(spec, digest),
        ROOT / "clients" / "typescript" / "src" / "index.ts": typescript(spec, digest),
    }
    if "--check" in sys.argv[1:]:
        stale = [p for p, text in files.items() if not p.exists() or p.read_text(encoding="utf-8") != text]
        for p in stale:
            print(f"{p.relative_to(ROOT)} is not what scripts/gen-clients.py generates from the contract")
        return 1 if stale else 0
    for p, text in files.items():
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
